"""Generate bpmn-alignments.ttl: mappings to earlier BPMN ontologies.

    py scripts/generate_alignments.py MAP

MAP holds local copies of the three ontologies (not committed, their licences
differ from ours):

  sbpmn.ttl  sBPMN 2.0, https://github.com/sBPMN/2.0 (docs/ontology.ttl), CC BY 4.0
  fbk.owl    FBK BPMN 2.0 ontology v0.4, copy in https://github.com/InES-Mannheim/spa-core, CC BY-NC-SA
  bbo.owl    BBO v1.5, https://github.com/ProfTuan/BBO, GPL-3.0

Only skos:exactMatch, and only to terms that exist in those files: a mapping
by IRI copies nothing from them. No owl:equivalentClass on purpose: that would
import BBO's disjointness axioms into every graph that loads the mapping.
"""
from __future__ import annotations

import sys
from pathlib import Path

import rdflib
from rdflib import OWL, RDF

WORTEL = Path(__file__).resolve().parents[1]
NS = "https://w3id.org/bpmn#"
BRONNEN = [
    ("sbpmn.ttl", "turtle", "sBPMN 2.0 (Krause 2025)", "https://github.com/sBPMN/2.0"),
    ("fbk.owl", "xml", "FBK BPMN 2.0 ontology v0.4 (Rospocher, Ghidini, Serafini)", "http://dkm.fbk.eu/index.php/BPMN2_Ontology"),
    ("bbo.owl", "xml", "BBO, BPMN 2.0 Based Ontology v1.5 (Annane, Aussenac-Gilles, Kamel)", "http://w3id.org/bbo"),
]


def sleutel(iri: str) -> str:
    naam = iri.rsplit("#", 1)[-1].rsplit("/", 1)[-1]
    if naam.startswith("has_"):
        naam = naam[4:]
    return naam.replace("_", "").lower()


def main() -> None:
    map_ = Path(sys.argv[1])
    eigen = rdflib.Graph()
    eigen.parse(WORTEL / "bpmn.ttl", format="turtle")
    klassen = {sleutel(str(s)): str(s) for s in eigen.subjects(RDF.type, OWL.Class) if str(s).startswith(NS)}
    eigenschappen = {sleutel(str(s)): str(s) for t in (OWL.ObjectProperty, OWL.DatatypeProperty)
                     for s in eigen.subjects(RDF.type, t) if str(s).startswith(NS)}
    uit = ["@prefix skos: <http://www.w3.org/2004/02/skos/core#> .",
           "@prefix dct: <http://purl.org/dc/terms/> .",
           "@prefix owl: <http://www.w3.org/2002/07/owl#> .", "",
           "# GENERATED by scripts/generate_alignments.py. skos:exactMatch only, to terms that",
           "# exist in the source files; no axioms or labels are copied from them.", "",
           f"<{NS.rstrip('#')}/alignments> a owl:Ontology ;",
           '    dct:title "BPMN 2.0 in RDF: alignments to earlier BPMN ontologies"@en .', ""]
    tellingen = []
    for bestand, formaat, naam, bron in BRONNEN:
        g = rdflib.Graph()
        g.parse(map_ / bestand, format=formaat)
        hun_k = {sleutel(str(s)): str(s) for s in g.subjects(RDF.type, OWL.Class) if isinstance(s, rdflib.URIRef)}
        hun_p = {sleutel(str(s)): str(s) for t in (OWL.ObjectProperty, OWL.DatatypeProperty)
                 for s in g.subjects(RDF.type, t) if isinstance(s, rdflib.URIRef)}
        nk = np_ = 0
        uit.append(f"# {naam}: {bron}")
        for k, onze in sorted(klassen.items()):
            if k in hun_k:
                uit.append(f"<{onze}> skos:exactMatch <{hun_k[k]}> .")
                nk += 1
        for k, onze in sorted(eigenschappen.items()):
            if k in hun_p:
                uit.append(f"<{onze}> skos:exactMatch <{hun_p[k]}> .")
                np_ += 1
        uit.append("")
        tellingen.append((naam, nk, len(klassen), np_, len(eigenschappen)))
    (WORTEL / "bpmn-alignments.ttl").write_text("\n".join(uit), encoding="utf-8", newline="\n")
    for naam, nk, tk, np_, tp in tellingen:
        print(f"{naam}: {nk} van {tk} klassen, {np_} van {tp} eigenschappen")


if __name__ == "__main__":
    main()
